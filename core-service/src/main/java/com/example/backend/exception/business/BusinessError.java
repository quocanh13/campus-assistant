package com.example.backend.exception.business;

import org.springframework.http.HttpStatus;
import org.springframework.http.HttpStatusCode;
import org.springframework.lang.NonNull;

import lombok.Getter;

@Getter
public enum BusinessError{
    DUPLICATE_USERNAME(HttpStatus.CONFLICT),
    USER_NOT_FOUND(HttpStatus.NOT_FOUND),
    INVALID_PASSWORD(HttpStatus.UNAUTHORIZED),
    INVALID_USER_ID(HttpStatus.BAD_REQUEST),
    CREATE_USER_DENIED(HttpStatus.FORBIDDEN),
    ACCESS_DENIED(HttpStatus.BAD_REQUEST),

    ACCOUNT_NOT_FOUND(HttpStatus.NOT_FOUND),
    ACCOUNT_EMAIL_EXISTS(HttpStatus.CONFLICT),
    INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),

    STUDENT_EXISTS(HttpStatus.CONFLICT),
    STUDENT_ACCOUNT_EXISTS(HttpStatus.CONFLICT),
    INVALID_STUDENT_ACCOUNT_ROLE(HttpStatus.BAD_REQUEST),
    CREATE_STUDENT_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    STUDENT_NOT_FOUND(HttpStatus.NOT_FOUND),
    STUDENT_PROFILE_NOT_FOUND(HttpStatus.NOT_FOUND),
    UPDATE_STUDENT_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    DELETE_STUDENT_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),

    CONVERSATION_EXISTS(HttpStatus.CONFLICT),
    CONVERSATION_NOT_FOUND(HttpStatus.NOT_FOUND),
    CONVERSATION_ACCESS_DENIED(HttpStatus.FORBIDDEN),
    CREATE_CONVERSATION_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    UPDATE_CONVERSATION_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    DELETE_CONVERSATION_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),

    MESSAGE_EXISTS(HttpStatus.CONFLICT),
    MESSAGE_NOT_FOUND(HttpStatus.NOT_FOUND),
    CREATE_MESSAGE_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),

    DOCUMENT_NOT_FOUND(HttpStatus.NOT_FOUND),
    DOCUMENT_ACCESS_DENIED(HttpStatus.FORBIDDEN),
    INVALID_DOCUMENT_TYPE(HttpStatus.BAD_REQUEST),
    INVALID_DOCUMENT_VALIDITY(HttpStatus.BAD_REQUEST),
    UPLOAD_DOCUMENT_DENIED(HttpStatus.FORBIDDEN),
    DELETE_DOCUMENT_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    UPDATE_DOCUMENT_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    
    UNIT_NOT_FOUND(HttpStatus.NOT_FOUND),

    MAJOR_NOT_FOUND(HttpStatus.NOT_FOUND),
    MAJOR_EXISTS(HttpStatus.CONFLICT);

    @NonNull
    private final HttpStatusCode statusCode;
    private BusinessError(@NonNull HttpStatusCode statusCode){
        this.statusCode = statusCode;
    }
}
